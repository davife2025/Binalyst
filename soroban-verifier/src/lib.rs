#[cfg(test)]
mod tests {
    use super::*;
    use soroban_sdk::{testutils::Address as _, Env};

    #[test]
    fn test_initialise() {
        let env   = Env::default();
        let contract_id = env.register_contract(None, BinalystVerifier);
        let client = BinalystVerifierClient::new(&env, &contract_id);
        let admin  = Address::generate(&env);
        client.initialise(&admin);
        assert_eq!(client.admin(), admin);
        assert_eq!(client.proof_count(), 0);
    }

    #[test]
    fn test_json_bool_true() {
        let buf = br#"{"valid":true,"dry_run":false}"#;
        assert_eq!(json_bool(buf, b"\"valid\""),   Some(true));
        assert_eq!(json_bool(buf, b"\"dry_run\""), Some(false));
    }

    #[test]
    fn test_json_str_field() {
        let buf = br#"{"symbol":"BTC","action":"BUY"}"#;
        assert_eq!(json_str_field(buf, b"\"symbol\""), Some(b"BTC".as_ref()));
        assert_eq!(json_str_field(buf, b"\"action\""), Some(b"BUY".as_ref()));
    }

    #[test]
    fn test_json_f64_field() {
        let buf = br#"{"amount_usdt":1000.5,"drawdown_pct":4.75}"#;
        assert!((json_f64_field(buf, b"\"amount_usdt\"").unwrap() - 1000.5).abs() < 0.01);
        assert!((json_f64_field(buf, b"\"drawdown_pct\"").unwrap() - 4.75).abs() < 0.01);
    }

    #[test]
    fn test_placeholder_image_id_panics() {
        // Confirm that submitting a proof with the placeholder image_id
        // returns PlaceholderImageId error (not a cryptographic failure).
        // This guards against accidentally deploying with the placeholder.
        let env = Env::default();
        let contract_id = env.register_contract(None, BinalystVerifier);
        let client = BinalystVerifierClient::new(&env, &contract_id);
        let admin  = Address::generate(&env);
        client.initialise(&admin);

        let result = client.try_verify_trade_proof(
            &admin,
            &Bytes::from_array(&env, &[0u8; 300]),
            &Bytes::from_slice(&env, br#"{"valid":true}"#),
        );
        assert!(result.is_err());
    }
}
