// soroban-verifier/src/lib.rs
//
// Binalyst ZK Verifier — Soroban smart contract (Stellar)
//
// What this contract does:
//   • Accepts a RISC Zero receipt (seal + journal) as bytes
//   • Verifies the Groth16 proof using Stellar Protocol 26 BN254 host functions
//   • Parses the journal (TradeProofOutput JSON) to extract public outputs
//   • Emits a VerifyEvent on success so the Next.js app can confirm on-chain
//   • Stores a compact audit log of verified trade proofs
//
// Protocol 26 ("Yardstick") host functions used:
//   bn254_g1_add, bn254_g1_mul, bn254_g1_msm,
//   bn254_g2_add, bn254_g2_mul,
//   bn254_pairing_check,
//   bn254_fr_add, bn254_fr_mul, bn254_fr_pow
//
// References:
//   https://github.com/NethermindEth/stellar-risc0-verifier/
//   https://jamesbachini.com/stellar-risc-zero-games/
//   https://dev.risczero.com/

