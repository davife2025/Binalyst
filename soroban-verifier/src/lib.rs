// ─────────────────────────────────────────────────────────────────────────────
// On-chain proof record
// ─────────────────────────────────────────────────────────────────────────────

#[contracttype]
#[derive(Clone, Debug)]
pub struct ProofRecord {
    /// Sequential proof index (1-based)
    pub index:         u32,
    /// Verified trade symbol (e.g. "BTC")
    pub symbol:        String,
    /// "BUY" or "SELL"
    pub action:        String,
    /// Trade amount in USDT (scaled ×100 for integer storage, e.g. 1000.00 → 100000)
    pub amount_usdt_cents: i64,
    /// Rule ID that fired
    pub rule_id:       String,
    /// Rule name
    pub rule_name:     String,
    /// Portfolio drawdown % at decision time (scaled ×100, e.g. 4.75% → 475)
    pub drawdown_bps:  i64,
    /// Whether this was a dry-run (simulation)
    pub dry_run:       bool,
    /// Unix timestamp (ms) from the journal
    pub decided_at_ms: u64,
    /// Ledger sequence when verified on-chain
    pub verified_at_ledger: u32,
    /// First 8 bytes of the RISC Zero receipt seal (compact fingerprint)
    pub receipt_fingerprint: BytesN<8>,
}

// ─────────────────────────────────────────────────────────────────────────────
// Contract
// ─────────────────────────────────────────────────────────────────────────────

#[contract]
pub struct BinalystVerifier;

#[contractimpl]
impl BinalystVerifier {

    // ── Initialise ────────────────────────────────────────────────────────────

    /// Deploy once. Sets the contract admin (the Binalyst backend keypair).
    pub fn initialise(env: Env, admin: Address) {
        if env.storage().instance().has(&Symbol::new(&env, KEY_ADMIN)) {
            panic_with_error!(&env, VerifierError::Unauthorised);
        }
        env.storage().instance().set(&Symbol::new(&env, KEY_ADMIN), &admin);
        env.storage().instance().set(&Symbol::new(&env, KEY_PROOF_COUNT), &0u32);
        env.storage().instance().set(
            &Symbol::new(&env, KEY_PROOF_LOG),
            &Map::<u32, ProofRecord>::new(&env),
        );
        env.events().publish(
            (Symbol::new(&env, "Initialised"),),
            admin,
        );
    }

    // ── Main verification entry point ──────────────────────────────────────

    /// Verify a RISC Zero receipt and record the proof on-chain.
    ///
    /// Parameters:
    ///   seal    — the Groth16 proof bytes (from the RISC Zero receipt)
    ///   journal — the raw journal bytes committed by the guest (JSON-encoded
    ///             TradeProofOutput)
    ///
    /// Returns the on-chain proof index on success.
    pub fn verify_trade_proof(
        env:     Env,
        caller:  Address,
        seal:    Bytes,
        journal: Bytes,
    ) -> u32 {
        caller.require_auth();

        // ── Guard: placeholder image_id ──────────────────────────────────────
        if BINALYST_IMAGE_ID == [0u8; 32] {
            panic_with_error!(&env, VerifierError::PlaceholderImageId);
        }

        // ── 1. Verify the Groth16 proof ───────────────────────────────────────
        // Uses Stellar Protocol 26 BN254 host functions via the
        // NethermindEth risc0 verifier pattern.
        verify_groth16_proof(&env, &seal, &journal);

        // ── 2. Parse journal → public outputs ─────────────────────────────────
        let record = parse_journal_and_build_record(&env, &journal, &seal);

        // ── 3. Persist to storage ─────────────────────────────────────────────
        let count: u32 = env.storage().instance()
            .get(&Symbol::new(&env, KEY_PROOF_COUNT))
            .unwrap_or(0);

        if count >= MAX_LOG_ENTRIES {
            panic_with_error!(&env, VerifierError::LogFull);
        }

        let new_count = count + 1;
        let mut log_map: Map<u32, ProofRecord> = env.storage().instance()
            .get(&Symbol::new(&env, KEY_PROOF_LOG))
            .unwrap_or(Map::new(&env));

        let mut full_record = record;
        full_record.index = new_count;
        full_record.verified_at_ledger = env.ledger().sequence();

        log_map.set(new_count, full_record.clone());
        env.storage().instance().set(&Symbol::new(&env, KEY_PROOF_LOG),   &log_map);
        env.storage().instance().set(&Symbol::new(&env, KEY_PROOF_COUNT), &new_count);

        // ── 4. Emit event ──────────────────────────────────────────────────────
        env.events().publish(
            (Symbol::new(&env, "TradeProofVerified"),),
            (
                new_count,
                full_record.symbol.clone(),
                full_record.action.clone(),
                full_record.decided_at_ms,
                full_record.dry_run,
            ),
        );

        log!(&env, "Binalyst ZK: proof #{} verified — {} {} decided_at={}",
            new_count,
            full_record.action,
            full_record.symbol,
            full_record.decided_at_ms,
        );

        new_count
    }

    // ── Read helpers ───────────────────────────────────────────────────────

    /// Return the total number of verified proofs.
    pub fn proof_count(env: Env) -> u32 {
        env.storage().instance()
            .get(&Symbol::new(&env, KEY_PROOF_COUNT))
            .unwrap_or(0)
    }

    /// Return a specific proof record by index (1-based).
    pub fn get_proof(env: Env, index: u32) -> ProofRecord {
        let log_map: Map<u32, ProofRecord> = env.storage().instance()
            .get(&Symbol::new(&env, KEY_PROOF_LOG))
            .unwrap_or(Map::new(&env));
        log_map.get(index).unwrap()
    }

    /// Return the last N proof records (most recent first).
    pub fn get_recent_proofs(env: Env, n: u32) -> Vec<ProofRecord> {
        let count: u32 = env.storage().instance()
            .get(&Symbol::new(&env, KEY_PROOF_COUNT))
            .unwrap_or(0);
        let log_map: Map<u32, ProofRecord> = env.storage().instance()
            .get(&Symbol::new(&env, KEY_PROOF_LOG))
            .unwrap_or(Map::new(&env));

        let mut results = Vec::new(&env);
        let start = if count > n { count - n + 1 } else { 1 };
        let mut i = count;
        while i >= start {
            if let Some(rec) = log_map.get(i) {
                results.push_back(rec);
            }
            if i == 0 { break; }
            i -= 1;
        }
        results
    }

    /// Return the contract admin address.
    pub fn admin(env: Env) -> Address {
        env.storage().instance()
            .get(&Symbol::new(&env, KEY_ADMIN))
            .unwrap()
    }
}

